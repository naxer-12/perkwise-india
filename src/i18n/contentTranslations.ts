export function getLocalizedCardCap(cardId: string, language: LanguageCode): string {
  const capLabelMap: Record<LanguageCode, string> = {
    en: 'Cap',
    hi: 'सीमा',
    gu: 'મર્યાદા',
    mr: 'मर्यादा',
    ta: 'வரம்பு',
    te: 'పరిమితి',
    bn: 'সীমা',
    kn: 'ಮಿತಿ',
  };
  const capWord = capLabelMap[language] || 'Cap';

  switch (cardId) {
    case 'hdfc-millennia-debit':
      return `${capWord}: ₹400/mo (₹4.8k/yr)`;
    case 'sbi-cashback':
      return `${capWord}: ₹5,000/mo`;
    case 'airtel-axis':
      return `${capWord}: ₹250+₹250/mo`;
    case 'amazon-pay-icici':
      return language === 'en' ? 'Cap: Unlimited' : `${capWord}: ${language === 'hi' ? 'असीमित' : language === 'gu' ? 'અમર્યાદિત' : 'Unlimited'}`;
    case 'hdfc-millennia':
      return `${capWord}: ₹1,000/mo`;
    default:
      return `${capWord}: Standard`;
  }
}
