export function getLocalizedCard(card: CreditCard, language: LanguageCode): CreditCard & { tagline?: string } {
  const trans = CARD_TRANSLATIONS[card.id]?.[language];
  if (!trans) return card;

  return {
    ...card,
    whyThisCardWins: trans.whyWins,
    tagline: trans.tagline,
  };
}

