export function getLocalizedArticle(article: Article, language: LanguageCode): Article & { keyAlphaTakeaway?: string } {
  const trans = ARTICLE_TRANSLATIONS[article.id]?.[language];
  const diffMap = DIFFICULTY_TRANSLATIONS[language] || DIFFICULTY_TRANSLATIONS.en;
  const localizedDifficulty = (diffMap[article.difficulty] || article.difficulty) as any;

  // Localize readTime
  let localizedReadTime = article.readTime;
  if (language !== 'en') {
    const num = article.readTime.match(/\d+/)?.[0] || '5';
    const unitMap: Record<LanguageCode, string> = {
      en: 'min read',
      hi: 'मिनट पठन',
      gu: 'મિનિટ વાંચન',
      mr: 'मिनिटे वाचन',
      ta: 'நிமிட வாசிப்பு',
      te: 'నిమిషాల పఠనం',
      bn: 'মিনিট পাঠ',
      kn: 'ನಿಮಿಷ ಓದುವಿಕೆ',
    };
    localizedReadTime = `${num} ${unitMap[language] || 'min read'}`;
  }

  if (!trans) {
    return {
      ...article,
      difficulty: localizedDifficulty,
      readTime: localizedReadTime,
    };
  }

  return {
    ...article,
    title: trans.title,
    summary: trans.summary,
    keyAlphaTakeaway: trans.takeaway,
    difficulty: localizedDifficulty,
    readTime: localizedReadTime,
  };
}

